import { randomUUID } from 'node:crypto';
import { createReadStream } from 'node:fs';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { Readable } from 'node:stream';

/**
 * Where inspection photos are kept.
 * - On Vercel (BLOB_READ_WRITE_TOKEN set): Vercel Blob with private access.
 * - Elsewhere: files on disk (UPLOAD_DIR, default ./uploads). On government servers this
 *   is replaced by MinIO/S3 behind the same two functions.
 * Photos are never linked directly; the API streams them to signed-in users only.
 */
export type Storage = 'blob' | 'local';

const EXTENSIONS: Record<string, string> = { 'image/jpeg': 'jpg', 'image/png': 'png', 'image/webp': 'webp' };
export const ALLOWED_PHOTO_TYPES = Object.keys(EXTENSIONS);

const uploadDir = () => process.env.UPLOAD_DIR ?? path.resolve(process.cwd(), 'uploads');
const useBlob = () => Boolean(process.env.BLOB_READ_WRITE_TOKEN);

export async function storePhoto(data: Buffer, contentType: string, inspectionId: string): Promise<{ storage: Storage; key: string }> {
  const name = `${randomUUID()}.${EXTENSIONS[contentType] ?? 'bin'}`;
  if (useBlob()) {
    const { put } = await import('@vercel/blob');
    const result = await put(`inspections/${inspectionId}/${name}`, data, {
      access: 'private',
      contentType,
      addRandomSuffix: false,
    });
    return { storage: 'blob', key: result.pathname };
  }
  await mkdir(uploadDir(), { recursive: true });
  await writeFile(path.join(uploadDir(), name), data);
  return { storage: 'local', key: name };
}

export async function readPhoto(storage: Storage, key: string): Promise<Readable | null> {
  if (storage === 'blob') {
    const { get } = await import('@vercel/blob');
    const result = await get(key, { access: 'private' });
    if (!result || result.statusCode !== 200 || !result.stream) return null;
    return Readable.fromWeb(result.stream as import('node:stream/web').ReadableStream);
  }
  // Keys are generated by storePhoto; refuse anything else (no path traversal).
  if (!/^[0-9a-f-]{36}\.(jpg|png|webp)$/.test(key)) return null;
  return createReadStream(path.join(uploadDir(), key));
}

export async function deletePhoto(storage: Storage, key: string): Promise<void> {
  if (storage === 'blob') {
    const { del } = await import('@vercel/blob');
    await del(key);
    return;
  }
  if (!/^[0-9a-f-]{36}\.(jpg|png|webp)$/.test(key)) return;
  const { unlink } = await import('node:fs/promises');
  await unlink(path.join(uploadDir(), key)).catch(() => undefined);
}
